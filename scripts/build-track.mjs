// Converts bacinger/f1-circuits (MIT) GeoJSON into normalised SVG polylines for the 2026 circuits.
// Usage: node scripts/build-track.mjs scripts/geo/index.json > src/data/tracks/geometry.ts
import { readFileSync } from 'node:fs';
const IDS = ['au-1953','cn-2004','jp-1962','bh-2002','sa-2021','us-2022','ca-1978','mc-1929','es-1991','at-1969',
  'gb-1948','be-1925','hu-1986','nl-1948','it-1922','es-2026','az-2016','sg-2008','us-2012','mx-1962','br-1940',
  'us-2023','qa-2004','ae-2009'];
const gj = JSON.parse(readFileSync(process.argv[2], 'utf8'));
const out = {};
for (const id of IDS) {
  const f = gj.features.find(x => x.properties.id === id);
  if (!f) throw new Error('missing ' + id);
  const coords = f.geometry.coordinates;
  const lat0 = coords.reduce((s, c) => s + c[1], 0) / coords.length;
  const k = Math.cos((lat0 * Math.PI) / 180);
  let pts = coords.map(([lon, lat]) => [lon * k, -lat]);
  const xs = pts.map(p => p[0]), ys = pts.map(p => p[1]);
  const minX = Math.min(...xs), minY = Math.min(...ys);
  const w = Math.max(...xs) - minX, h = Math.max(...ys) - minY;
  const S = 1000 / Math.max(w, h), PAD = 40;
  pts = pts.map(([x, y]) => [+((x - minX) * S + PAD).toFixed(1), +((y - minY) * S + PAD).toFixed(1)]);
  out[id] = { viewBox: [Math.round(w * S + PAD * 2), Math.round(h * S + PAD * 2)], points: pts };
}
console.log(`// Generated by scripts/build-track.mjs from bacinger/f1-circuits (MIT). Do not edit.
export const GEOMETRY: Record<string, { viewBox: readonly [number, number]; points: [number, number][] }> = ${JSON.stringify(out)};`);
