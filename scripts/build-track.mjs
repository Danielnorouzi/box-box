// Converts a bacinger/f1-circuits GeoJSON LineString into a normalised SVG polyline.
// Usage: node scripts/build-track.mjs scripts/qa-2004.geojson lusail > src/data/tracks/lusail.geom.ts
import { readFileSync } from 'node:fs';
const [, , file, id] = process.argv;
const gj = JSON.parse(readFileSync(file, 'utf8'));
const coords = gj.features[0].geometry.coordinates;
const lat0 = coords.reduce((s, c) => s + c[1], 0) / coords.length;
const k = Math.cos((lat0 * Math.PI) / 180);
let pts = coords.map(([lon, lat]) => [lon * k, -lat]);
const xs = pts.map(p => p[0]), ys = pts.map(p => p[1]);
const minX = Math.min(...xs), minY = Math.min(...ys);
const w = Math.max(...xs) - minX, h = Math.max(...ys) - minY;
const S = 1000 / Math.max(w, h), PAD = 40;
pts = pts.map(([x, y]) => [+((x - minX) * S + PAD).toFixed(1), +((y - minY) * S + PAD).toFixed(1)]);
const vw = Math.round(w * S + PAD * 2), vh = Math.round(h * S + PAD * 2);
console.log(`// Generated by scripts/build-track.mjs from bacinger/f1-circuits (MIT). Do not edit.
export const ${id}Geometry = {
  viewBox: [${vw}, ${vh}] as const,
  points: ${JSON.stringify(pts)} as [number, number][],
};`);
